/* Build a year-level test by sampling up to two distinct random questions per
   topic (if a topic's pool has fewer than 2 questions, take all it has).
   Records which topicId each question came from for focus recommendations. */
function buildYearTest(yearKey) {
  const topics = window.CURRICULUM[yearKey].topics;
  const out = [];
  for (const t of topics) {
    const pool = QUIZ_BY_TOPIC[t.id];
    if (!pool || !pool.length) continue;
    // Shuffle a copy of the pool indices and take the first min(2, pool.length)
    const indices = pool.map((_, idx) => idx);
    for (let i = indices.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [indices[i], indices[j]] = [indices[j], indices[i]];
    }
    const picks = indices.slice(0, Math.min(2, indices.length));
    for (const pi of picks) {
      out.push({ ...pool[pi], topicId: t.id, topicTitle: t.title });
    }
  }
  // shuffle order
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

window.buildYearTest = buildYearTest;
